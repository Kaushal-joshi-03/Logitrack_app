// Default fallback coordinate (Central India)
export const DEFAULT_COORDINATE = [23.0000, 77.0000];

export function getCityCoordinate(cityName) {
  if (!cityName) return DEFAULT_COORDINATE;
  const trimmed = cityName.trim();
  if (cityCoordinates[trimmed]) return cityCoordinates[trimmed];

  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  const key = Object.keys(cityCoordinates).find(
    (k) => k.toLowerCase() === lower
  );
  if (key) return cityCoordinates[key];

  // Substring match
  const subKey = Object.keys(cityCoordinates).find((k) =>
    k.toLowerCase().includes(lower) || lower.includes(k.toLowerCase())
  );
  if (subKey) return cityCoordinates[subKey];

  return DEFAULT_COORDINATE;
}
